CREATE TABLE user_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    target_type VARCHAR(20) NOT NULL CHECK (target_type IN ('COMPANY', 'JOB', 'CANDIDATE')),
    target_id VARCHAR(36) NOT NULL,
    complaint TEXT NOT NULL CHECK (char_length(complaint) BETWEEN 10 AND 5000),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_REVIEW', 'RESOLVED', 'REJECTED')),
    processing_outcome TEXT,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_user_reports_newest ON user_reports(created_at DESC, id DESC);
CREATE INDEX idx_user_reports_filters ON user_reports(status, target_type, created_at DESC, id DESC);
